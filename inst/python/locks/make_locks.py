"""
Maintainer script: regenerates the explicit conda environments of canobsR (one per platform), used by
canobsR::canobs_setup(). With an explicit file, conda installs a fixed list of packages without solving
(a solve of arosics + gdal takes minutes and gigabytes of memory, and can differ between users).

    python make_locks.py /path/to/conda          (any platform: conda solves for the 4 platforms)

Then test canobs_setup() on Windows at least, and commit the 4 files canobs-<platform>.txt.
"""
import concurrent.futures as cf
import json
import os
import subprocess
import sys
import urllib.request

SPECS = ["python=3.12", "arosics>=1.14", "gdal>=3.10", "numpy", "pillow", "pip", "setuptools"]
PLATFORMS = ["win-64", "linux-64", "osx-64", "osx-arm64"]
HERE = os.path.dirname(os.path.abspath(__file__))


def exists(url):
    try:
        with urllib.request.urlopen(urllib.request.Request(url, method="HEAD"), timeout=60) as r:
            return r.status == 200
    except Exception:
        return False


def lock(conda, sub):
    env = dict(os.environ, CONDA_SUBDIR=sub, CONDA_OVERRIDE_OSX="13.0", CONDA_OVERRIDE_GLIBC="2.28")
    out = subprocess.run([conda, "create", "--dry-run", "--json", "-n", "canobs_lock", "--override-channels",
                          "-c", "conda-forge"] + SPECS, env=env, capture_output=True, text=True)
    links = json.loads(out.stdout)["actions"]["LINK"]

    def url(x):
        base = f"{x['base_url']}/{x['platform']}/{x['dist_name']}"
        for ext in (".conda", ".tar.bz2"):
            if exists(base + ext):
                return base + ext
        raise RuntimeError(f"no package file for {base}")

    with cf.ThreadPoolExecutor(16) as ex:
        urls = list(ex.map(url, links))
    v = {x["name"]: x["version"] for x in links}
    with open(os.path.join(HERE, f"canobs-{sub}.txt"), "w") as f:
        f.write(f"# Explicit conda environment of canobsR for {sub} (no solving needed: conda create --file).\n")
        f.write(f"# Generated by inst/python/locks/make_locks.py, specs: {' '.join(SPECS)}\n")
        f.write(f"# python {v['python']}, gdal {v['gdal']}, arosics {v['arosics']}, numpy {v['numpy']}; "
                f"{len(links)} packages\n@EXPLICIT\n")
        f.write("\n".join(urls) + "\n")
    print(sub, len(links), "packages")


if __name__ == "__main__":
    for p in PLATFORMS:
        lock(sys.argv[1], p)
